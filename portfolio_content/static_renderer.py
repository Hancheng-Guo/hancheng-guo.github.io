LINK_PRESENTATION = {
    "github": ("github", "Code"),
    "techDoc": ("file-pdf", "Docs"),
    "bilibili": ("bilibili", "Bilibili"),
    "youtube": ("youtube", "YouTube"),
}


def _project_blocks(blocks: list[dict[str, Any]]) -> str:
    parts: list[str] = []
    for block in blocks:
        kind = block.get("type")
        if kind == "heading":
            level = min(6, max(2, int(block.get("level", 2))))
            parts.append(f'<h{level}>{markdown_inline(block.get("text"))}</h{level}>')
        elif kind == "paragraph":
            parts.append(f'<div class="project-detail-desc markdown-body">{markdown_block(block.get("text"))}</div>')
        elif kind == "image":
            caption = f'<figcaption>{markdown_inline(block.get("caption"))}</figcaption>' if block.get("caption") else ""
            parts.append(f'<figure><img class="project-img" src="../../{escape(str(block.get("src", "")), quote=True)}" alt="{markdown_text(block.get("alt"))}" loading="lazy" decoding="async">{caption}</figure>')
        elif kind == "gallery":
            figures = []
            for image in block.get("images", []):
                caption = f'<figcaption>{markdown_inline(image.get("caption"))}</figcaption>' if image.get("caption") else ""
                figures.append(f'<figure><img class="project-img" src="../../{escape(str(image.get("src", "")), quote=True)}" alt="{markdown_text(image.get("alt"))}" loading="lazy">{caption}</figure>')
            parts.append('<div class="project-gallery">' + "".join(figures) + "</div>")
        elif kind == "list":
            tag = "ol" if block.get("ordered") else "ul"
            parts.append(f'<{tag}>' + "".join(f'<li>{markdown_inline(item)}</li>' for item in block.get("items", [])) + f'</{tag}>')
        elif kind == "quote":
            source = f'<cite>{markdown_inline(block.get("source"))}</cite>' if block.get("source") else ""
            parts.append(f'<blockquote>{markdown_block(block.get("text"))}{source}</blockquote>')
        elif kind == "metrics":
            values = "".join(f'<dt>{markdown_inline(item.get("label"))}</dt><dd>{markdown_inline(item.get("value"))}</dd>' for item in block.get("items", []))
            parts.append(f'<dl class="project-metrics">{values}</dl>')
        elif kind == "video" and str(block.get("url", "")).startswith("https://"):
            parts.append(f'<a href="{escape(str(block["url"]), quote=True)}" target="_blank" rel="noopener noreferrer">{markdown_inline(block.get("title") or block["url"])}</a>')
    return "".join(parts)


def render_project(portfolio: Any, project: dict[str, Any]) -> str:
    content = project["locales"]["en"]
    visible = [item for item in portfolio.projects if item.get("status") != "draft"]
    position = next((index for index, item in enumerate(visible) if item.get("id") == project.get("id")), -1)
    adjacent = []
    if position > 0:
        previous = visible[position - 1]
        adjacent.append(f'<a class="project-adjacent-link previous" href="../../{escape(str(previous["page"]), quote=True)}"><span class="project-adjacent-label">&lt; Previous</span><span class="project-adjacent-name">{markdown_inline(previous["locales"]["en"]["title"])}</span></a>')
    if 0 <= position < len(visible) - 1:
        following = visible[position + 1]
        adjacent.append(f'<a class="project-adjacent-link next" href="../../{escape(str(following["page"]), quote=True)}"><span class="project-adjacent-label">Next &gt;</span><span class="project-adjacent-name">{markdown_inline(following["locales"]["en"]["title"])}</span></a>')
    links = []
    for link in project.get("links", []):
        presentation = LINK_PRESENTATION.get(str(link.get("type")))
        if not presentation or not str(link.get("url", "")).startswith("https://"):
            continue
        icon, default_label = presentation
        label = markdown_inline(link.get("label") or default_label)
        links.append(f'<a class="publish-link" href="{escape(str(link["url"]), quote=True)}" target="_blank" rel="noopener noreferrer">{_icon(icon)}<span>{label}</span></a>')
    links_html = '<div class="publish-links-wrapper"><div class="publish-links">' + "".join(links) + "</div></div>" if links else ""
    favicon = _favicon(portfolio.favicon, "../../")
    robots = '<meta name="robots" content="noindex, nofollow">' if project.get("status") == "draft" else ""
    page_title_source = f'{localized(content.get("title"))} - {localized(portfolio.site_name)}'
    page_title = markdown_text(page_title_source)
    metadata = _metadata(
        title=page_title_source,
        description=content.get("summary", ""),
        canonical_path=str(project.get("page", "")),
        og_type="article",
        image_path=str(project.get("thumbnail", {}).get("src", "")) or None,
        structured_data={
            "@context": "https://schema.org",
            "@type": "CreativeWork",
            "name": markdown_plain(content.get("title")),
            "description": markdown_plain(content.get("summary")),
            "url": f'{SITE_ORIGIN}/{project.get("page", "")}',
        },
    )
    return f'''<!DOCTYPE html>
{MARKER}
<html lang="en" data-theme="dark"><head><meta charset="UTF-8"><meta name="viewport" content="width=device-width, initial-scale=1.0"><title>{page_title}</title>{robots}{metadata}{favicon}<script>document.documentElement.setAttribute('data-theme', localStorage.getItem('theme') || 'dark');</script><link rel="stylesheet" href="../../assets/css/style.css"></head><body data-page="project" data-project-id="{escape(str(project.get("id")), quote=True)}">{_nav(portfolio, "../../")}<main class="section-padding"><div class="container"><div class="card project-detail-card"><div class="project-container"><a class="back-link" href="../../index.html#projects">&lt; Back to Projects</a><h2>{markdown_inline(content.get("title"))}</h2>{_project_blocks(content.get("blocks", []))}{links_html}<nav class="project-adjacent" aria-label="Project navigation">{"".join(adjacent)}</nav></div></div></div></main>{_footer(portfolio)}<script type="module" src="../../assets/js/app.js"></script></body></html>'''


def write_text_atomic(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile("w", encoding="utf-8", dir=path.parent, delete=False, newline="\n") as handle:
        handle.write(content + "\n")
        temporary = Path(handle.name)
    os.replace(temporary, path)
