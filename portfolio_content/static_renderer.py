_UNDERLINE = re.compile(r"(?<![\w_])_(?!_)(?=\S)([^_\n]*?\S)_(?![\w_])")
_UNSAFE_HREF = re.compile(r'\s+href="(?!https?://|mailto:|tel:|#|/|\.\.?/)[^"]*"', re.I)
_VOID_TAGS = {"area", "base", "br", "col", "embed", "hr", "img", "input", "link", "meta", "source", "track", "wbr"}
_RAW_TAGS = {"script", "style", "pre", "code", "textarea"}
_INLINE_TAGS = {"a", "abbr", "b", "br", "cite", "code", "em", "i", "mark", "small", "span", "strong", "sub", "sup", "time", "u"}
_SIMPLE_TEXT_TAGS = {"title", "h1", "h2", "h3", "h4", "h5", "h6", "p", "dt", "dd", "figcaption", "li"}


def _tag_end(source: str, start: int) -> int:
    """Return the end of an HTML tag while respecting quoted attributes."""
    quote: str | None = None
    index = start + 1
    while index < len(source):
        char = source[index]
        if quote:
            if char == quote:
                quote = None
        elif char in {"'", '"'}:
            quote = char
        elif char == ">":
            return index + 1
        index += 1
    return len(source)


def _tag_name(token: str) -> str | None:
    match = re.match(r"<\s*/?\s*([a-zA-Z][\w:-]*)", token)
    return match.group(1).lower() if match else None


def _html_tree(document: str) -> list[dict[str, Any]]:
    """Parse only the small HTML subset emitted by this generator, losslessly."""
    root: list[dict[str, Any]] = []
    stack: list[dict[str, Any]] = []

    def append(node: dict[str, Any]) -> None:
        (stack[-1]["children"] if stack else root).append(node)

    index = 0
    while index < len(document):
        if document[index] != "<":
            next_tag = document.find("<", index)
            next_tag = len(document) if next_tag < 0 else next_tag
            append({"kind": "text", "value": document[index:next_tag]})
            index = next_tag
            continue
        if document.startswith("<!--", index):
            end = document.find("-->", index + 4)
            end = len(document) if end < 0 else end + 3
            append({"kind": "raw", "value": document[index:end]})
            index = end
            continue
        end = _tag_end(document, index)
        token = document[index:end]
        name = _tag_name(token)
        if not name:
            append({"kind": "raw", "value": token})
            index = end
            continue
        if token.startswith("</"):
            if stack and stack[-1]["name"] == name:
                stack[-1]["close"] = token
                stack.pop()
            else:
                append({"kind": "raw", "value": token})
            index = end
            continue
        if name in _RAW_TAGS:
            close_match = re.search(rf"</\s*{re.escape(name)}\s*>", document[end:], re.I)
            raw_end = end + close_match.end() if close_match else len(document)
            append({"kind": "raw", "value": document[index:raw_end]})
            index = raw_end
            continue
        node = {"kind": "tag", "name": name, "open": token, "close": "", "children": []}
        append(node)
        if name not in _VOID_TAGS and not token.rstrip().endswith("/>"):
            stack.append(node)
        index = end
    return root


def pretty_html(document: str) -> str:
    """Format generated HTML using a quote-aware, lossless token tree.

    It deliberately never rewrites text nodes or raw script/style/pre/code
    payloads, so Markdown inline content and JavaScript/CSS whitespace retain
    their original semantics.
    """
    def inline(node: dict[str, Any]) -> str | None:
        if node["kind"] == "raw":
            return node["value"] if "\n" not in node["value"] else None
        if node["kind"] == "text":
            return node["value"] if "\n" not in node["value"] else None
        pieces: list[str] = []
        for child in node["children"]:
            piece = inline(child)
            if piece is None:
                return None
            pieces.append(piece)
        if node["name"] in _INLINE_TAGS or node["name"] in _SIMPLE_TEXT_TAGS:
            return node["open"] + "".join(pieces) + node["close"]
        return None

    lines: list[str] = []
    def render(node: dict[str, Any], depth: int) -> None:
        prefix = "  " * depth
        compact = inline(node)
        if compact is not None:
            lines.append(prefix + compact)
            return
        if node["kind"] == "raw":
            if node["value"].strip():
                lines.append(prefix + node["value"])
            return
        if node["kind"] == "text":
            # Newlines in normal HTML text collapse to whitespace in the
            # browser.  Split them only to avoid formatter-created blank lines
            # with trailing indentation; raw/pre/code payloads bypass this.
            for piece in node["value"].splitlines():
                if piece.strip():
                    lines.append(prefix + piece.strip())
            return
        lines.append(prefix + node["open"])
        for child in node["children"]:
            if child["kind"] == "text" and not child["value"].strip():
                continue
            render(child, depth + 1)
        if node["close"]:
            lines.append(prefix + node["close"])

    for node in _html_tree(document):
        if node["kind"] == "text" and not node["value"].strip():
            continue
        render(node, 0)
    return "\n".join(line.rstrip() for line in lines).strip()


def localized(value: Any, language: str = "en") -> Any:
    if isinstance(value, dict) and ("en" in value or "zh" in value):
        return value.get(language, value.get("en", ""))
    return value


def _prepare_markdown(value: Any) -> str:
    text = str(localized(value) or "")
    return _UNDERLINE.sub(lambda match: f"MDUNDERLINEOPEN{match.group(1)}MDUNDERLINECLOSE", text)


def markdown_block(value: Any) -> str:
    rendered = str(markdown2.markdown(
        _prepare_markdown(value),
        safe_mode="escape",
        extras=["break-on-newline", "cuddled-lists", "fenced-code-blocks", "strike", "tables"],
    ))
    rendered = rendered.replace("MDUNDERLINEOPEN", "<u>").replace("MDUNDERLINECLOSE", "</u>")
    return _UNSAFE_HREF.sub("", rendered).strip()


def markdown_inline(value: Any) -> str:
    rendered = markdown_block(value)
    if rendered.startswith("<p>") and rendered.endswith("</p>") and rendered.count("<p>") == 1:
        return rendered[3:-4].rstrip("\n")
    return rendered


def markdown_plain(value: Any) -> str:
    return unescape(re.sub(r"<[^>]+>", "", markdown_inline(value)))


def markdown_text(value: Any) -> str:
    return escape(markdown_plain(value), quote=True)


def format_month(value: str, language: str = "en") -> str:
    year, month = (int(part) for part in value.split("-"))
    return f"{year}年{month}月" if language == "zh" else f"{month_abbr[month]} {year}"


def format_date_range(value: Any, language: str = "en") -> str:
    if not value:
        return ""
    if isinstance(value, str):
        start, end = value, None
    else:
        start, end = value.get("start"), value.get("end")
    if not start:
        return ""
    if isinstance(value, dict) and not end:
        month = format_month(start, language)
        return f"{start[:4]}年{int(start[5:])}月 至今" if language == "zh" else f"Since {month}"
    start_text = format_month(start, language)
    return f"{start_text} – {format_month(end, language)}" if end and end != start else start_text


def format_full_date(value: str, language: str = "en") -> str:
    parsed = Date.fromisoformat(value)
    return f"{parsed.year}年{parsed.month}月{parsed.day}日" if language == "zh" else f"{month_abbr[parsed.month]} {parsed.day}, {parsed.year}"


def _icon(name: str) -> str:
    safe_name = re.sub(r"[^a-z0-9-]", "", name.lower())
    # Keep the generated document useful when it is opened directly from disk.
    # Chromium-family browsers block external SVGs used as CSS masks for a
    # ``file://`` document, which used to make every static control glyph
    # disappear.  These are first-party, allow-listed assets, so embed their
    # SVG markup in generated HTML; hydrated pages may still use the compact
    # CSS-mask spans created by JavaScript over HTTP.
    icon_path = Path(__file__).resolve().parents[1] / "assets" / "icons" / f"{safe_name}.svg"
    try:
        markup = icon_path.read_text(encoding="utf-8").strip()
    except OSError:
        return f'<span class="svg-icon icon-{safe_name}" aria-hidden="true"></span>'
    svg_start = re.search(r"<svg\b", markup)
    if not svg_start:
        return f'<span class="svg-icon icon-{safe_name}" aria-hidden="true"></span>'
    # Some local SVGs contain an XML declaration or repository comments.
    # Generated pages are HTML documents, so embed the SVG element only.
    markup = markup[svg_start.start():]
    return re.sub(
        r"<svg\b",
        f'<svg class="svg-icon svg-icon--inline icon-{safe_name}" aria-hidden="true" focusable="false"',
        markup,
        count=1,
    )


def _favicon(path: str | None, prefix: str) -> str:
    return f'  <link rel="icon" href="{prefix}{escape(path, quote=True)}">\n' if path else ""


def _metadata(
    *,
    title: Any,
    description: Any,
    canonical_path: str,
    og_type: str,
    image_path: str | None = None,
    structured_data: dict[str, Any] | None = None,
) -> str:
    safe_title = markdown_text(title)
    safe_description = markdown_text(description)
    canonical = f"{SITE_ORIGIN}/{canonical_path.lstrip('/')}" if canonical_path else f"{SITE_ORIGIN}/"
    image = f'<meta property="og:image" content="{SITE_ORIGIN}/{escape(image_path, quote=True)}">' if image_path else ""
    structured = ""
    if structured_data:
        payload = json.dumps(structured_data, ensure_ascii=False, separators=(",", ":")).replace("<", "\\u003c")
        structured = f'<script type="application/ld+json">{payload}</script>'
    return f'''<meta name="description" content="{safe_description}">
<meta property="og:title" content="{safe_title}">
<meta property="og:description" content="{safe_description}">
<meta property="og:type" content="{escape(og_type, quote=True)}">
<meta property="og:url" content="{canonical}">
{image}<link rel="canonical" href="{canonical}">
{structured}'''


