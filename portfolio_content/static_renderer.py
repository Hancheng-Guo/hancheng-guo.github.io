def _download(resume: dict[str, Any], prefix: str) -> str:
    url = localized(resume.get("url"))
    if not url:
        return ""
    external = str(url).startswith(("http://", "https://"))
    href = str(url) if external else prefix + str(url)
    attrs = ' target="_blank" rel="noopener noreferrer"' if external else (' download' if resume.get("download", True) else "")
    label = markdown_inline(resume.get("label") or "Download CV")
    return f'<a class="publish-link primary-action" href="{escape(href, quote=True)}"{attrs}>{_icon("file-pdf")}<span>{label}</span></a>'


def _contacts(portfolio: Any, prefix: str = "") -> str:
    parts: list[str] = []
    email = localized(portfolio.profile.get("email"))
    if email:
        safe_email = escape(str(email), quote=True)
        parts.append(f'<div class="contact-item email-contact-item"><a class="email-contact-link" href="mailto:{safe_email}" aria-label="{safe_email}">{_icon("envelope")}<span>{escape(str(email))}</span></a></div>')
    social = []
    for contact in portfolio.contacts:
        label = markdown_inline(contact.get("label"))
        plain_label = markdown_text(contact.get("label"))
        social.append(f'<div class="contact-item"><a href="{escape(str(contact.get("url", "")), quote=True)}" aria-label="{plain_label}" title="{plain_label}" target="_blank" rel="noopener noreferrer">{_icon(str(contact.get("icon", "")))}<span class="visually-hidden">{label}</span></a></div>')
    if social:
        parts.append('<div class="social-contact-group">' + "".join(social) + "</div>")
    return "".join(parts)


def _entry(entry: dict[str, Any], title_field: str, detail_fields: tuple[str, ...]) -> str:
    title = markdown_inline(entry.get(title_field, ""))
    date_text = format_date_range(entry.get("date"))
    details = [markdown_inline(entry.get(field, "")) for field in detail_fields if localized(entry.get(field, ""))]
    pieces: list[str] = []
    if date_text:
        pieces.append(f'<time class="entry-date">{escape(date_text)}</time>')
    pieces.extend(f'<span class="entry-detail">{detail}</span>' for detail in details)
    detail_html = '<span class="entry-separator"> · </span>'.join(pieces)
    details = f'<p>{detail_html}</p>' if detail_html else ""
    return f'<article class="content-entry"><h3>{title}</h3>{details}</article>'


def _publication_entries(items: list[dict[str, Any]]) -> str:
    return "".join(_entry(item, "title", ("venue",)) for item in items)


def _education_entry(entry: dict[str, Any]) -> str:
    """Render the intentional three-line Education CV format.

    Accept legacy raw entries as well as the canonical fields emitted by the
    current builder. This matters for users who retained an older site.json.
    """
    position = entry.get("position") or entry.get("degree") or entry.get("institution") or ""
    institute = entry.get("institute") or entry.get("institution") or ""
    location = entry.get("location") or ""
    detail = entry.get("detail") or ""
    first_line = f'<strong>{markdown_inline(position)}</strong>'
    place = [markdown_inline(value) for value in (institute, location) if localized(value)]
    if place:
        first_line += ", " + ", ".join(place)
    date_text = format_date_range(entry.get("date"))
    date_line = f'<time class="entry-date">{escape(date_text)}</time>' if date_text else ""
    detail_line = f'<p class="education-detail">{markdown_inline(detail)}</p>' if localized(detail) else ""
    return f'<article class="content-entry education-entry"><h3 class="education-heading">{first_line}</h3>{date_line}{detail_line}</article>'


def _work_entry(entry: dict[str, Any]) -> str:
    """Render Work Experience in the same three-line layout as Education."""
    position = entry.get("position") or ""
    company = entry.get("company") or ""
    location = entry.get("location") or ""
    detail = entry.get("detail") or ""
    first_line = f'<strong>{markdown_inline(position)}</strong>'
    place = [markdown_inline(value) for value in (company, location) if localized(value)]
    if place:
        first_line += ", " + ", ".join(place)
    date_text = format_date_range(entry.get("date"))
    date_line = f'<time class="entry-date">{escape(date_text)}</time>' if date_text else ""
    detail_line = f'<p class="work-detail">{markdown_inline(detail)}</p>' if localized(detail) else ""
    return f'<article class="content-entry work-entry"><h3 class="work-heading">{first_line}</h3>{date_line}{detail_line}</article>'


def _profile_asset(profile: dict[str, Any], key: str) -> str | None:
    """Return an explicitly configured profile asset, never a placeholder."""
    value = profile.get(key)
    return value.strip() if isinstance(value, str) and value.strip() else None


def _hero_attributes(hero_background: str | None) -> str:
    if not hero_background:
        return ""
    # This value is consumed by the stylesheet's pseudo-element, so browsers
    # resolve its URL relative to ``assets/css/style.css``.  Translate the
    # configured repository-relative asset path to that base.  A leading site
    # slash would instead break direct file previews and project-site mounts.
    css_path = posixpath.relpath(hero_background.lstrip("/"), start="assets/css")
    css_url = f"url({json.dumps(css_path)})"
    return f' data-hero-background="true" style="--hero-background-image: {escape(css_url, quote=True)}"'


def _project_card(project: dict[str, Any]) -> str:
    content = project["locales"]["en"]
    date_text = format_date_range(project.get("date"))
    tags = "".join(f'<span class="project-tag">{markdown_inline(tag)}</span>' for tag in project.get("tags", []))
    href = escape(str(project["page"]), quote=True)
    image = project.get("thumbnail", {})
    alt = markdown_text(localized(image.get("alt")))
    # The hidden time is deliberately retained for undated projects.  The
    # client renderer uses this exact node too, which prevents hydration from
    # changing the footer's layout or DOM shape.
    date_element = f'<time class="project-date">{escape(date_text)}</time>' if date_text else '<time class="project-date" hidden></time>'
    return f'''<article class="card" tabindex="0" data-project-href="{href}"><div class="project-thumbnail-wrapper"><img class="project-thumbnail" src="{escape(str(image.get("src", "")), quote=True)}" alt="{alt}" loading="lazy" decoding="async"></div><div class="project-info"><div class="project-copy"><h3>{markdown_inline(content.get("title"))}</h3><p class="project-summary">{markdown_inline(content.get("summary"))}</p></div><div class="project-meta"><div class="project-tags">{tags}</div><div class="project-card-footer"><a class="project-link" href="{href}">View Details</a>{date_element}</div></div></div></article>'''


def _timeline(portfolio: Any) -> tuple[str, bool]:
    events = list(reversed([event for event in portfolio.timeline if event.get("status") != "draft"]))
    parts = []
    for index, event in enumerate(events):
        extra = " timeline-extra" if index >= 8 else ""
        parts.append(f'<div class="timeline-item{extra}"><div class="timeline-dot"></div><div class="timeline-summary"><span class="timeline-date">{escape(format_date_range(event.get("date")))}</span><h3>{markdown_inline(event.get("title"))}</h3></div><div class="timeline-content"><p>{markdown_inline(event.get("description"))}</p></div></div>')
    return "".join(parts), len(events) > 8


