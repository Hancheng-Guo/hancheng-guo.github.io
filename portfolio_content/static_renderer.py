def _footer(portfolio: Any) -> str:
    author = markdown_inline(portfolio.author)
    copyright_text = markdown_inline(portfolio.copyright_text)
    suffix = f", {copyright_text}" if copyright_text else ""
    updated = format_full_date(portfolio.last_update_date)
